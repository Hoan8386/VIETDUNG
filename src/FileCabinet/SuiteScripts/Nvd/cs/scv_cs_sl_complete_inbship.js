    function saveRecord(scriptContext) {
        let arrSl = getDataSlResult(scriptContext.currentRecord);
        if(arrSl.length == 0){
            alert('Bạn chưa chọn hàng nào');
            return false;
        }

        return true;
    }

    const getDataSlResult = (curRec) => {
        let results = [];
        let fieldIds = [
            'custpage_col_check', 'custpage_col_hhdv', 'custpage_col_unit', 'custpage_col_sl_can_nhap', 'custpage_col_sl_da_nhap', 'custpage_col_ori_lineid'
        ];
        let sl = 'custpage_sl_result';
        for(let i = 0; i < curRec.getLineCount(sl); i++){
            let checkbox = curRec.getSublistValue(sl, 'custpage_col_check', i);
            if(checkbox){
                let obj = {};
                fieldIds.forEach(fieldId => {
                    obj[fieldId] = curRec.getSublistValue(sl, fieldId, i)
                })

                results.push(obj)
            }
        }
        return results;
    }

